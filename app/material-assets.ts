import {
  object,
  string,
  validateSchemaValue,
  type MaterialAsset,
} from "./extensions/registry";

export const ASSET_LIMITS = {
  count: 40,
  bytes: 4_000_000,
  totalBytes: 8_000_000,
  dimension: 8000,
  pixels: 16_000_000,
  svgBytes: 800_000,
} as const;
export const TYPST_MAX_REQUEST_BYTES = 14_000_000;
export const MATERIAL_ASSET_SCHEMA = object({
  assetId: string({ required: true, minLength: 1, maxLength: 80 }),
  filename: string({ required: true, minLength: 1, maxLength: 200 }),
  mimeType: string({
    required: true,
    enum: ["image/png", "image/jpeg", "image/svg+xml"],
  }),
  size: {
    type: "integer",
    required: true,
    minimum: 1,
    maximum: ASSET_LIMITS.bytes,
  },
  width: {
    type: "integer",
    required: true,
    minimum: 1,
    maximum: ASSET_LIMITS.dimension,
  },
  height: {
    type: "integer",
    required: true,
    minimum: 1,
    maximum: ASSET_LIMITS.dimension,
  },
  source: string({ maxLength: 2000 }),
  license: string({ maxLength: 2000 }),
  attribution: string({ maxLength: 2000 }),
  alt: string({ required: true, maxLength: 2000 }),
  data: string({
    required: true,
    minLength: 1,
    maxLength: Math.ceil(ASSET_LIMITS.bytes / 3) * 4,
    description:
      "Validated base64 transport payload outside Markdown; never generated by an authoring prompt.",
  }),
});
export class MaterialAssetError extends Error {
  code = "UNSAFE_MATERIAL_ASSET";
  stage = "request" as const;
  constructor(message: string) {
    super(message);
    this.name = "MaterialAssetError";
  }
}
const fail: (message: string) => never = (message) => {
  throw new MaterialAssetError(message);
};
export const assetIdIsSafe = (id: string) =>
  /^[a-z][a-z0-9_-]{0,79}$/u.test(id);
export function createMaterialId(
  prefix: "asset" | "figure",
  cryptoSource: Partial<
    Pick<Crypto, "randomUUID" | "getRandomValues">
  > = globalThis.crypto
) {
  // randomUUID requires a secure browser context; getRandomValues remains
  // available in the isolated HTTP preview and supplies the same 128 bits.
  if (typeof cryptoSource?.randomUUID === "function")
    return `${prefix}-${cryptoSource.randomUUID()}`;
  if (typeof cryptoSource?.getRandomValues !== "function")
    throw new Error("安全な画像IDを生成できませんでした。");
  const bytes = cryptoSource.getRandomValues(new Uint8Array(16));
  return `${prefix}-${Array.from(bytes, (byte) =>
    byte.toString(16).padStart(2, "0")
  ).join("")}`;
}
export function bytesToBase64(bytes: Uint8Array) {
  let result = "";
  for (let i = 0; i < bytes.length; i += 16384)
    result += String.fromCharCode(...bytes.subarray(i, i + 16384));
  return btoa(result);
}
export function base64ToBytes(value: string) {
  if (
    !value ||
    value.length > Math.ceil(ASSET_LIMITS.bytes / 3) * 4 ||
    value.length % 4 !== 0 ||
    !/^[A-Za-z0-9+/]+={0,2}$/u.test(value)
  )
    fail("画像payloadは上限内の正規base64にしてください。");
  try {
    return Uint8Array.from(atob(value), (char) => char.charCodeAt(0));
  } catch {
    return fail("画像payloadを復号できません。");
  }
}
const safeSize = (width: number, height: number) => {
  if (
    !Number.isInteger(width) ||
    !Number.isInteger(height) ||
    width < 1 ||
    height < 1 ||
    width > ASSET_LIMITS.dimension ||
    height > ASSET_LIMITS.dimension ||
    width * height > ASSET_LIMITS.pixels
  )
    fail("画像サイズは各辺8000px以下、合計1600万pixel以下にしてください。");
  return { width, height };
};
const view = (bytes: Uint8Array) =>
  new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let crc = n;
  for (let bit = 0; bit < 8; bit++)
    crc = crc & 1 ? 0xedb88320 ^ (crc >>> 1) : crc >>> 1;
  return crc >>> 0;
});
const crc32 = (bytes: Uint8Array) => {
  let crc = 0xffffffff;
  for (const byte of bytes) crc = CRC_TABLE[(crc ^ byte) & 255] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
};
function pngSize(bytes: Uint8Array) {
  const signature = [137, 80, 78, 71, 13, 10, 26, 10];
  if (bytes.length < 45 || signature.some((v, i) => bytes[i] !== v))
    return fail("PNGの署名が不正です。");
  const data = view(bytes);
  let cursor = 8,
    header = false,
    image = false,
    end = false;
  let dimensions: { width: number; height: number } | undefined;
  for (
    let chunks = 0;
    cursor + 12 <= bytes.length && chunks < 20000;
    chunks++
  ) {
    const length = data.getUint32(cursor),
      type = new TextDecoder().decode(bytes.subarray(cursor + 4, cursor + 8));
    if (length > ASSET_LIMITS.bytes || cursor + 12 + length > bytes.length)
      fail("PNG chunkが破損しています。");
    if (
      crc32(bytes.subarray(cursor + 4, cursor + 8 + length)) !==
      data.getUint32(cursor + 8 + length)
    )
      fail("PNG chunkのCRCが一致しません。");
    if (type === "IHDR") {
      if (header || cursor !== 8 || length !== 13) fail("PNG IHDRが不正です。");
      header = true;
      dimensions = safeSize(
        data.getUint32(cursor + 8),
        data.getUint32(cursor + 12)
      );
    }
    if (type === "IDAT") image = true;
    if (type === "IEND") {
      end = true;
      cursor += 12 + length;
      break;
    }
    cursor += 12 + length;
  }
  if (!header || !image || !end || cursor !== bytes.length)
    fail("PNGの必須chunkまたは終端が不正です。");
  return dimensions!;
}
function jpegSize(bytes: Uint8Array) {
  if (
    bytes.length < 12 ||
    bytes[0] !== 255 ||
    bytes[1] !== 216 ||
    bytes.at(-2) !== 255 ||
    bytes.at(-1) !== 217
  )
    return fail("JPEGの署名または終端が不正です。");
  const data = view(bytes);
  let cursor = 2;
  for (
    let segments = 0;
    cursor + 4 < bytes.length && segments < 20000;
    segments++
  ) {
    if (bytes[cursor++] !== 255) fail("JPEG markerが不正です。");
    while (bytes[cursor] === 255) cursor++;
    const marker = bytes[cursor++];
    if (marker === 218 || marker === 217) break;
    if (marker === 1 || (marker >= 208 && marker <= 215)) continue;
    const length = data.getUint16(cursor);
    if (length < 2 || cursor + length > bytes.length)
      fail("JPEG segmentが破損しています。");
    if (
      [
        192, 193, 194, 195, 197, 198, 199, 201, 202, 203, 205, 206, 207,
      ].includes(marker)
    ) {
      if (length < 8) fail("JPEG寸法segmentが不正です。");
      return safeSize(data.getUint16(cursor + 5), data.getUint16(cursor + 3));
    }
    cursor += length;
  }
  return fail("JPEGの寸法を確認できません。");
}
const SVG_TAGS = new Set(
  "svg g defs rect circle ellipse line polyline polygon path text tspan linearGradient radialGradient stop clipPath mask title desc marker".split(
    " "
  )
);
const SVG_ATTRS = new Set(
  "xmlns xmlns:xlink id x y x1 y1 x2 y2 cx cy r rx ry width height viewBox preserveAspectRatio d points transform fill stroke stroke-width stroke-linecap stroke-linejoin stroke-miterlimit stroke-dasharray stroke-dashoffset opacity fill-opacity stroke-opacity fill-rule clip-rule clip-path mask font-family font-size font-style font-weight text-anchor dominant-baseline dx dy offset stop-color stop-opacity gradientUnits gradientTransform xlink:href href marker-start marker-mid marker-end markerWidth markerHeight refX refY orient style role aria-label".split(
    " "
  )
);
function decodeEntities(value: string) {
  if (/&(?!amp;|lt;|gt;|quot;|apos;|#\d+;|#x[0-9a-fA-F]+;)/u.test(value))
    fail("SVGに未定義のentityがあります。");
  return value.replace(
    /&(amp|lt|gt|quot|apos|#\d+|#x[0-9a-fA-F]+);/gu,
    (_, entity: string) => {
      if (entity.startsWith("#")) {
        const n =
          entity[1] === "x"
            ? parseInt(entity.slice(2), 16)
            : Number(entity.slice(1));
        if (n < 1 || n > 0x10ffff) fail("SVG entityが不正です。");
        return String.fromCodePoint(n);
      }
      return (
        { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" } as Record<
          string,
          string
        >
      )[entity];
    }
  );
}
/** Reject unsafe XML, keep supported safe SVG byte-for-byte except XML prolog. */
export function sanitizeAssetSvg(input: string) {
  if (new TextEncoder().encode(input).length > ASSET_LIMITS.svgBytes)
    fail("SVGは800KB以下にしてください。");
  if (
    /<!|<\?(?!xml\s)/iu.test(input) ||
    /[\u0000-\u0008\u000b\u000c\u000e-\u001f]/u.test(input)
  )
    fail("SVGのDTD・entity宣言・CDATA・処理命令は使用できません。");
  const svg = input
    .replace(/^\uFEFF/u, "")
    .replace(/^\s*<\?xml\s[^?]*\?>/u, "")
    .trim();
  const tokens = [...svg.matchAll(/<(?:[^"'>]|"[^"]*"|'[^']*')*>/gu)];
  let cursor = 0;
  const stack: string[] = [];
  let root = "";
  let nodes = 0;
  for (const match of tokens) {
    const between = svg.slice(cursor, match.index);
    if (/[<>]/u.test(between)) fail("SVGのXML構造が不正です。");
    decodeEntities(between);
    cursor = match.index! + match[0].length;
    const tag = match[0].match(/^<\/?([A-Za-z][A-Za-z0-9]*)\b/u)?.[1];
    if (!tag || !SVG_TAGS.has(tag))
      fail(
        "未許可のSVG要素です。script・foreignObject・外部imageは使えません。"
      );
    if (++nodes > 12000) fail("SVG node数が12000を超えています。");
    const closing = match[0].startsWith("</"),
      self = match[0].endsWith("/>");
    if (closing) {
      if (!new RegExp(`^</${tag}\\s*>$`).test(match[0]) || stack.pop() !== tag)
        fail("SVGの閉じタグが一致しません。");
      continue;
    }
    if (!stack.length) {
      if (root) fail("SVG rootが複数あります。");
      root = match[0];
      if (tag !== "svg") fail("SVG rootはsvgにしてください。");
    }
    const raw = match[0].slice(tag.length + 1, self ? -2 : -1);
    let consumed = 0;
    const names = new Set<string>();
    for (const attribute of raw.matchAll(
      /\s+([A-Za-z_:][A-Za-z0-9_.:-]*)\s*=\s*("[^"]*"|'[^']*')/gu
    )) {
      if (raw.slice(consumed, attribute.index).trim())
        fail("SVG属性が不正です。");
      consumed = attribute.index! + attribute[0].length;
      const name = attribute[1],
        value = decodeEntities(attribute[2].slice(1, -1));
      if (!SVG_ATTRS.has(name) || names.has(name))
        fail(`未許可または重複するSVG属性: ${name}`);
      names.add(name);
      if (
        (name === "xmlns" && value !== "http://www.w3.org/2000/svg") ||
        (name === "xmlns:xlink" && value !== "http://www.w3.org/1999/xlink")
      )
        fail("SVG namespaceが不正です。");
      if (name === "href" || name === "xlink:href") {
        if (!/^#[A-Za-z_][\w.-]{0,99}$/u.test(value))
          fail("SVG外部参照は禁止です。");
      }
      if (
        /(?:javascript:|data:|https?:|file:|@import|expression\s*\(|\\)/iu.test(
          value
        ) &&
        !name.startsWith("xmlns")
      )
        fail("SVGに外部参照または実行可能な値があります。");
      for (const url of value.matchAll(/url\s*\(([^)]*)\)/giu))
        if (!/^#[A-Za-z_][\w.-]{0,99}$/u.test(url[1]))
          fail("SVG urlは内部ID参照だけにしてください。");
      if (name === "style")
        for (const declaration of value.split(";").filter((s) => s.trim())) {
          const [property, ...rest] = declaration.split(":");
          if (
            !SVG_ATTRS.has(property.trim()) ||
            !rest.length ||
            rest.join(":").includes(":")
          )
            fail("SVG styleには許可された描画属性だけを指定してください。");
        }
    }
    if (raw.slice(consumed).trim()) fail("SVGの属性を解析できません。");
    if (!self) stack.push(tag);
  }
  if (!root || stack.length || svg.slice(cursor).trim())
    fail("SVGのXML構造または終端が不正です。");
  const read = (key: string) =>
    root.match(new RegExp(`\\b${key}\\s*=\\s*["']([^"']+)["']`))?.[1];
  const bounds = read("viewBox")
    ?.split(/[\s,]+/u)
    .map(Number);
  const width = read("width"),
    height = read("height");
  const numberValue = (v: string | undefined) =>
    v && /^\d+(?:\.\d+)?(?:px)?$/u.test(v)
      ? Number(v.replace("px", ""))
      : undefined;
  const w = numberValue(width) ?? bounds?.[2],
    h = numberValue(height) ?? bounds?.[3];
  if (
    bounds &&
    (bounds.length !== 4 ||
      bounds.some((v) => !Number.isFinite(v)) ||
      bounds[2] <= 0 ||
      bounds[3] <= 0)
  )
    fail("SVG viewBoxが不正です。");
  return { svg, ...safeSize(Math.ceil(w ?? 0), Math.ceil(h ?? 0)) };
}
export function inspectImageBytes(
  bytes: Uint8Array,
  mimeType: MaterialAsset["mimeType"]
) {
  if (!bytes.length || bytes.length > ASSET_LIMITS.bytes)
    fail("画像は4MB以下にしてください。");
  if (mimeType === "image/png") return { ...pngSize(bytes), bytes };
  if (mimeType === "image/jpeg") return { ...jpegSize(bytes), bytes };
  if (mimeType === "image/svg+xml") {
    let source: string;
    try {
      source = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
    } catch {
      return fail("SVGはUTF-8で指定してください。");
    }
    const result = sanitizeAssetSvg(source);
    return { ...result, bytes: new TextEncoder().encode(result.svg) };
  }
  return fail("PNG・JPEG・SVGだけを利用できます。");
}
export function validateMaterialAssets(
  value: unknown
): Record<string, MaterialAsset> {
  if (value === undefined) return {};
  if (!value || typeof value !== "object" || Array.isArray(value))
    return fail("materialAssetsはIDからassetへのobjectにしてください。");
  const entries = Object.entries(value);
  if (entries.length > ASSET_LIMITS.count)
    fail("画像は40件以下にしてください。");
  const result: Record<string, MaterialAsset> = Object.create(null);
  let total = 0;
  for (const [key, item] of entries) {
    if (!item || typeof item !== "object" || Array.isArray(item))
      fail("asset設定が不正です。");
    const checked = validateSchemaValue(item, MATERIAL_ASSET_SCHEMA);
    if (checked.diagnostics.length)
      fail(`asset ${key}: ${checked.diagnostics[0].message}`);
    const asset = checked.value as unknown as MaterialAsset;
    if (!assetIdIsSafe(key) || asset.assetId !== key)
      fail(
        "assetIdは英小文字で始まる80文字以内の英小文字・数字・_・-にしてください。"
      );
    if (
      typeof asset.filename !== "string" ||
      asset.filename.length > 200 ||
      /[\/\\\u0000]/u.test(asset.filename)
    )
      fail("asset filenameにパスを指定できません。");
    for (const name of ["source", "license", "attribution", "alt"] as const)
      if (
        asset[name] !== undefined &&
        (typeof asset[name] !== "string" || asset[name]!.length > 2000)
      )
        fail(`asset ${name}は2000文字以下にしてください。`);
    if (typeof asset.alt !== "string" || typeof asset.data !== "string")
      fail("asset altとdataが必要です。");
    const bytes = base64ToBytes(asset.data);
    total += bytes.length;
    if (total > ASSET_LIMITS.totalBytes)
      fail("教材画像の合計は8MB以下にしてください。");
    const verified = inspectImageBytes(bytes, asset.mimeType);
    if (
      asset.width !== verified.width ||
      asset.height !== verified.height ||
      asset.size !== bytes.length
    )
      fail("画像の実寸・byte数とメタデータが一致しません。");
    result[key] = {
      assetId: key,
      filename: asset.filename,
      mimeType: asset.mimeType,
      size: verified.bytes.length,
      width: verified.width,
      height: verified.height,
      alt: asset.alt,
      source: asset.source,
      license: asset.license,
      attribution: asset.attribution,
      data: bytesToBase64(verified.bytes),
    };
  }
  return result;
}
export async function createMaterialAsset(
  file: File,
  assetId: string
): Promise<MaterialAsset> {
  if (file.size > ASSET_LIMITS.bytes) fail("画像は4MB以下にしてください。");
  const mime = (file.type ||
    (/\.svg$/iu.test(file.name)
      ? "image/svg+xml"
      : /\.png$/iu.test(file.name)
      ? "image/png"
      : /\.jpe?g$/iu.test(file.name)
      ? "image/jpeg"
      : "")) as MaterialAsset["mimeType"];
  const result = inspectImageBytes(
    new Uint8Array(await file.arrayBuffer()),
    mime
  );
  return {
    assetId,
    filename: file.name,
    mimeType: mime,
    size: result.bytes.length,
    width: result.width,
    height: result.height,
    alt: file.name,
    data: bytesToBase64(result.bytes),
  };
}
export const materialAssetPath = (asset: MaterialAsset) =>
  `assets/material-${asset.assetId}.${
    asset.mimeType === "image/png"
      ? "png"
      : asset.mimeType === "image/jpeg"
      ? "jpg"
      : "svg"
  }`;

export async function readBoundedBytes(
  request: Request,
  maximum = TYPST_MAX_REQUEST_BYTES
) {
  const reader = request.body?.getReader();
  if (!reader) return new Uint8Array();
  const chunks: Uint8Array[] = [];
  let total = 0;
  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.length;
    if (total > maximum) {
      await reader.cancel();
      throw Object.assign(
        new MaterialAssetError("PDF生成リクエストが14MBの上限を超えています。"),
        { code: "REQUEST_TOO_LARGE" }
      );
    }
    chunks.push(value);
  }
  const result = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    result.set(chunk, offset);
    offset += chunk.length;
  }
  return result;
}
